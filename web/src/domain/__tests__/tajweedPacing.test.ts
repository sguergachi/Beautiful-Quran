import { describe, expect, it } from 'vitest'
import {
  connection,
  connectionProgress,
  tajweedCurve,
  waslPrefixCompletion,
  waslPrefixStart,
} from '../tajweedPacing'

describe('Android tajweed pacing parity', () => {
  const dallin = 'ٱلضَّآلِّينَ'
  it('gates plain words, short words, empty text and non-Arabic', () => {
    for (const word of ['صِرَٰطَ', 'أَنۡعَمۡتَ', 'قُلۡ', '', 'hello'])
      expect(tajweedCurve(word)).toBeNull()
  })
  it('parks on the madd while the ordinary letters cruise', () => {
    const c = tajweedCurve(dallin)!
    expect(c.letterCount).toBe(5)
    expect(c.at(0.6) - c.at(0.42)).toBeLessThan(0.03)
    expect(c.at(0.3) - c.at(0.12)).toBeGreaterThan(0.15)
    expect(tajweedCurve(dallin, 1, { madd: false })).toBeNull()
    expect(tajweedCurve(dallin, 1, { cruiseCap: 1 })).toBeNull()
  })
  it('centres the faded edge on the held letter and settles at the voiced boundary', () => {
    const c = tajweedCurve('أَوۡلِيَآءَ')!
    for (const feather of [0, 0.4, 1.1092, 2]) {
      const wash = c.forWash(feather)
      for (const t of [0.65, 0.75]) {
        const centre = wash.at(t) * (1 + feather) - feather / 2
        expect(centre).toBeCloseTo(c.at(t), 6)
        expect(centre).toBeGreaterThanOrEqual(4 / 6)
        expect(centre).toBeLessThanOrEqual(5 / 6)
      }
      expect(wash.at(0)).toBe(0)
      expect(wash.at(1)).toBe(1)
    }
    expect(tajweedCurve('أَوۡلِيَآءَ', 0.8)!.forWash(1.1092).at(0.9)).toBe(1)
  })
  it('never exceeds the ordinary-letter cruise cap', () => {
    for (const cap of [1.1, 1.25, 1.6]) {
      const c = tajweedCurve(dallin, 1, { cruiseCap: cap })!
      for (let t = 0; t < 0.999; t += 0.001)
        expect((c.at(t + 0.001) - c.at(t)) / 0.001).toBeLessThanOrEqual(
          cap + 0.01,
        )
    }
  })
  it('holds ghunnah and waqf, but excludes a wasl-only hold from tarjīʿ', () => {
    expect(tajweedCurve('ٱلنَّاسِ')).toBeNull()
    expect(tajweedCurve('ٱلنَّاسِ', 1, { ghunnah: true })?.hasStrongHold).toBe(
      true,
    )
    expect(
      tajweedCurve('صِرَٰطَ', 1, { cruiseCap: 1, isAyahFinal: true })
        ?.hasStrongHold,
    ).toBe(true)
    expect(
      tajweedCurve(
        'وَقَالَ',
        1,
        { madd: false, waqf: false, ghunnah: false },
        'مِنۡ',
      )?.hasStrongHold,
    ).toBe(false)
  })
  it('folds silent QPC letters into the glide and preserves NFC maddah', () => {
    const c = tajweedCurve('قَالُوٓاْ')!
    expect(c.letterCount).toBe(4)
    expect(tajweedCurve('ٱلضَّآلِّينَ')!.at(0.6)).toBeCloseTo(
      tajweedCurve(dallin)!.at(0.6),
      6,
    )
    for (let t = 0; t < 1; t += 0.01)
      expect(c.at(t + 0.01)).toBeGreaterThanOrEqual(c.at(t) - 1e-9)
  })
  it('connects noon and both tanween families, never izhar or a vocalized noon', () => {
    expect(connection('مِنۡ', 'وَقَالَ')).not.toBeNull()
    expect(connection('رُّسُلٗا', 'مُّبَشِّرِينَ')).not.toBeNull()
    expect(connection('مِنۡ', 'هَٰذَا')).toBeNull()
    expect(connection('إِنَّ', 'وَقَالَ')).toBeNull()
  })
  it('short donors hand off an unfinished, smooth prefix without racing it', () => {
    const start = waslPrefixStart(100, 120),
      completion = waslPrefixCompletion(100, 120)
    expect(start).toBe(0.25)
    expect(completion).toBeLessThanOrEqual(0.45)
    expect(connectionProgress(start, start, completion)).toBe(0)
    expect(connectionProgress(1, start, completion)).toBeGreaterThan(0)
    expect(connectionProgress(1, start, completion)).toBeLessThan(1)
  })
})

